// Weak-scaling data for the HPCG chart: time per CG iteration = measured time / CG
// iterations, as in the thesis plotting script. 10 runs per configuration, 32³ points
// per GPU. Source CSVs (copied from the thesis plotting data): assets-src/hpcg/.
import { readFileSync, writeFileSync } from 'node:fs';

const read = (f) => readFileSync(new URL(`../assets-src/hpcg/${f}`, import.meta.url), 'utf8').replace(/^﻿/, '').trim().split('\n');
const iters = new Map(read('weak_scaling.csv').slice(1).map((l) => l.split(',').map(Number)));
const [head, ...rows] = read('measurements_weak_scaling.csv').map((l) => l.split(',').map(Number));

const median = (a) => {
  const s = [...a].sort((x, y) => x - y);
  return (s[(s.length - 1) >> 1] + s[s.length >> 1]) / 2;
};
const points = head.map((gpus, j) => {
  const t = rows.map((r) => r[j] / iters.get(gpus));
  return { gpus, ms: +median(t).toFixed(2), min: +Math.min(...t).toFixed(2), max: +Math.max(...t).toFixed(2) };
});

const out = `// Generated by scripts/build-weak-scaling.mjs from the thesis plotting data. Do not edit.
// Time per CG iteration in ms (median, min, max of 10 runs); 32³ grid points per GPU.
export const weakScaling = ${JSON.stringify(points, null, 2)};
`;
writeFileSync(new URL('../src/data/hpcg-weak-scaling.ts', import.meta.url), out);
console.table(points);
